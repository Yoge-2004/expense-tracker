package com.example.expensetracker.resilience;

import com.example.expensetracker.service.impl.DatabaseSnapshotServiceImpl;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import javax.sql.DataSource;
import java.lang.reflect.InvocationTargetException;
import java.lang.reflect.Proxy;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.Map;
import java.util.concurrent.atomic.AtomicBoolean;
import java.util.function.BooleanSupplier;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Runs the whole outage cycle with real components: the routing data source, the snapshot service and the
 * coordinator, with H2 standing in for both Neon and the local emergency store.
 */
@DisplayName("FallbackRecoveryCoordinator")
class FallbackRecoveryCoordinatorTest {

    @TempDir
    Path tmp;

    private final AtomicBoolean primaryDown = new AtomicBoolean(false);
    private JdbcDataSource primaryRaw;
    private ResilientRoutingDataSource routing;
    private DatabaseSnapshotServiceImpl snapshots;
    private FallbackRecoveryCoordinator coordinator;

    private void start() throws Exception {
        primaryRaw = new JdbcDataSource();
        primaryRaw.setURL("jdbc:h2:mem:coord_primary_" + System.nanoTime() + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1");
        primaryRaw.setUser("sa");
        primaryRaw.setPassword("");

        Path fallbackFile = tmp.resolve("fallback");
        JdbcDataSource fallbackRaw = new JdbcDataSource();
        fallbackRaw.setURL("jdbc:h2:file:" + fallbackFile + ";MODE=PostgreSQL;AUTO_SERVER=TRUE");
        fallbackRaw.setUser("sa");
        fallbackRaw.setPassword("");

        try (Connection c = primaryRaw.getConnection()) {
            exec(c, "CREATE TABLE users (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "email VARCHAR(100) NOT NULL, name VARCHAR(100), CONSTRAINT uk_email UNIQUE (email))");
            exec(c, "CREATE TABLE expenses (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "amount NUMERIC(19,2) NOT NULL, spent_on DATE, user_id BIGINT NOT NULL, "
                    + "CONSTRAINT fk_exp_user FOREIGN KEY (user_id) REFERENCES users(id))");
            exec(c, "INSERT INTO users (email, name) VALUES ('a@example.com', 'Asha')");
            exec(c, "INSERT INTO expenses (amount, spent_on, user_id) VALUES (120.50, DATE '2026-10-01', 1)");
        }

        routing = new ResilientRoutingDataSource(switchable(primaryRaw, primaryDown), fallbackRaw, 30, 60, 30, 5_000);
        snapshots = new DatabaseSnapshotServiceImpl(routing, fallbackFile.toString());
        coordinator = new FallbackRecoveryCoordinator(routing, snapshots);
    }

    /** What the app does at startup and after each good backup. */
    private void mirror() throws Exception {
        assertFalse(coordinator.prepareFallback());
        Path snapshot = tmp.resolve("mirror-" + System.nanoTime() + ".sqlite");
        assertTrue(snapshots.exportCurrentDatabase(snapshot) > 0);
        assertTrue(coordinator.refreshFallback(snapshot));
        coordinator.afterSnapshotRestored();
    }

    @Test
    @DisplayName("mirrors the primary into a fallback that has no entity tables yet")
    void mirrorsPrimaryIntoEmptyFallback() throws Exception {
        start();
        mirror();

        try (Connection f = routing.fallbackDataSource().getConnection()) {
            assertEquals(1, scalar(f, "SELECT COUNT(*) FROM users"));
            assertEquals(1, scalar(f, "SELECT COUNT(*) FROM expenses"));
        }
        assertEquals(0, coordinator.diagnostics().get("pendingFallbackChanges"));
    }

    @Test
    @DisplayName("carries writes made during an outage back to the primary and re-mirrors afterwards")
    void fullOutageCycle() throws Exception {
        start();
        mirror();

        primaryDown.set(true);
        try (Connection c = routing.getConnection()) {
            assertTrue(c.getMetaData().getURL().contains(":file:"), "outage traffic must be served by the fallback");
            exec(c, "INSERT INTO users (email, name) VALUES ('b@example.com', 'Bala')");
            long userId = scalar(c, "SELECT id FROM users WHERE email = 'b@example.com'");
            exec(c, "INSERT INTO expenses (amount, spent_on, user_id) VALUES (33.30, DATE '2026-10-05', " + userId + ")");
            exec(c, "UPDATE expenses SET amount = 130.00 WHERE id = 1");
        }
        assertEquals(ResilientRoutingDataSource.Mode.FALLBACK, routing.mode());

        primaryDown.set(false);
        waitFor(() -> {
            try (Connection c = routing.getConnection()) {
                return routing.mode() == ResilientRoutingDataSource.Mode.PRIMARY;
            } catch (SQLException e) {
                return false;
            }
        });

        try (Connection p = primaryRaw.getConnection()) {
            assertEquals(1, scalar(p, "SELECT COUNT(*) FROM users WHERE email = 'b@example.com'"));
            assertEquals(2, scalar(p, "SELECT COUNT(*) FROM expenses"));
            assertEquals("130.00", string(p, "SELECT amount FROM expenses WHERE id = 1"));
        }

        // The fallback is re-mirrored right after recovery, so a second outage starts from a clean baseline.
        waitFor(() -> {
            Map<String, Object> d = coordinator.diagnostics();
            return !"never".equals(d.get("lastRefreshAt")) && Integer.valueOf(0).equals(d.get("pendingFallbackChanges"));
        });
    }

    @Test
    @DisplayName("merges writes a previous run left in the fallback before a backup may replace the snapshot")
    void mergesLeftoverWritesBeforeBackup() throws Exception {
        start();
        mirror();

        try (Connection f = routing.fallbackDataSource().getConnection()) {
            exec(f, "INSERT INTO users (email, name) VALUES ('left@example.com', 'Leftover')");
        }
        assertEquals(ResilientRoutingDataSource.Mode.PRIMARY, routing.mode());

        assertTrue(coordinator.safeToOverwriteSnapshot());
        try (Connection p = primaryRaw.getConnection()) {
            assertEquals(1, scalar(p, "SELECT COUNT(*) FROM users WHERE email = 'left@example.com'"));
        }
    }

    @Test
    @DisplayName("is inert when the app runs against a single database")
    void inertWithoutRouting() {
        JdbcDataSource single = new JdbcDataSource();
        single.setURL("jdbc:h2:mem:single_" + System.nanoTime());
        FallbackRecoveryCoordinator inert = new FallbackRecoveryCoordinator(single, null);

        assertFalse(inert.isActive());
        assertFalse(inert.prepareFallback());
        assertTrue(inert.safeToOverwriteSnapshot());
        assertTrue(inert.refreshFallback(tmp.resolve("unused.sqlite")));
        assertEquals("SINGLE_DATABASE", inert.diagnostics().get("mode"));
    }

    // ------------------------------------------------------------ helpers

    private static DataSource switchable(DataSource delegate, AtomicBoolean down) {
        return (DataSource) Proxy.newProxyInstance(DataSource.class.getClassLoader(), new Class<?>[]{DataSource.class},
                (proxy, method, args) -> {
                    if (down.get() && method.getName().equals("getConnection")) {
                        throw new SQLException("compute quota exceeded");
                    }
                    try {
                        return method.invoke(delegate, args);
                    } catch (InvocationTargetException e) {
                        throw e.getCause();
                    }
                });
    }

    private static void exec(Connection c, String sql) throws SQLException {
        try (Statement s = c.createStatement()) {
            s.execute(sql);
        }
    }

    private static long scalar(Connection c, String sql) throws SQLException {
        try (Statement s = c.createStatement(); ResultSet rs = s.executeQuery(sql)) {
            assertTrue(rs.next(), "no row for: " + sql);
            return rs.getLong(1);
        }
    }

    private static String string(Connection c, String sql) throws SQLException {
        try (Statement s = c.createStatement(); ResultSet rs = s.executeQuery(sql)) {
            assertTrue(rs.next(), "no row for: " + sql);
            return rs.getString(1);
        }
    }

    private static void waitFor(BooleanSupplier condition) throws InterruptedException {
        long deadline = System.currentTimeMillis() + 10_000;
        while (System.currentTimeMillis() < deadline) {
            if (condition.getAsBoolean()) {
                return;
            }
            Thread.sleep(20);
        }
        throw new AssertionError("condition not met within 10 seconds");
    }
}
