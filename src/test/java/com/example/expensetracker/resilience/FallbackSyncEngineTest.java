package com.example.expensetracker.resilience;

import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import java.math.BigDecimal;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Exercises the fallback sync against two in-memory H2 databases standing in for Neon (primary) and the
 * local emergency store (fallback).
 */
@DisplayName("FallbackSyncEngine")
class FallbackSyncEngineTest {

    private final FallbackSyncEngine engine = new FallbackSyncEngine();
    private Connection primary;
    private Connection fallback;

    @BeforeEach
    void setUp() throws Exception {
        String id = Long.toString(System.nanoTime());
        primary = DriverManager.getConnection("jdbc:h2:mem:primary_" + id + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1", "sa", "");
        fallback = DriverManager.getConnection("jdbc:h2:mem:fallback_" + id + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1", "sa", "");

        exec(primary, "CREATE TABLE users (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "email VARCHAR(100) NOT NULL, name VARCHAR(100), CONSTRAINT uk_users_email UNIQUE (email))");
        exec(primary, "CREATE TABLE categories (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "name VARCHAR(50) NOT NULL, user_id BIGINT, "
                + "CONSTRAINT fk_cat_user FOREIGN KEY (user_id) REFERENCES users(id))");
        exec(primary, "CREATE TABLE expenses (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "amount NUMERIC(19,2) NOT NULL, description VARCHAR(255), spent_on DATE, created_at TIMESTAMP, "
                + "recurring BOOLEAN, user_id BIGINT NOT NULL, category_id BIGINT, "
                + "CONSTRAINT fk_exp_user FOREIGN KEY (user_id) REFERENCES users(id), "
                + "CONSTRAINT fk_exp_cat FOREIGN KEY (category_id) REFERENCES categories(id))");

        exec(primary, "INSERT INTO users (email, name) VALUES ('a@example.com', 'Asha')");
        exec(primary, "INSERT INTO users (email, name) VALUES ('b@example.com', 'Bala')");
        exec(primary, "INSERT INTO categories (name, user_id) VALUES ('Food', 1)");
        exec(primary, "INSERT INTO expenses (amount, description, spent_on, created_at, recurring, user_id, category_id) "
                + "VALUES (120.50, 'Lunch', DATE '2026-10-01', TIMESTAMP '2026-10-01 12:30:00', FALSE, 1, 1)");
        exec(primary, "INSERT INTO expenses (amount, description, spent_on, created_at, recurring, user_id, category_id) "
                + "VALUES (999.00, 'Rent', DATE '2026-10-02', TIMESTAMP '2026-10-02 09:00:00', TRUE, 2, NULL)");

        refreshFallback();
    }

    @AfterEach
    void tearDown() throws Exception {
        primary.close();
        fallback.close();
    }

    /** Mirrors what the app does after a good snapshot: schema, rows, baseline, identity gap. */
    private void refreshFallback() throws SQLException {
        engine.ensureSchema(primary, fallback);
        for (String table : List.of("USERS", "CATEGORIES", "EXPENSES")) {
            exec(fallback, "DELETE FROM " + table);
            copyRows(table);
        }
        engine.recordBaseline(fallback);
        engine.restartIdentities(fallback);
    }

    private void copyRows(String table) throws SQLException {
        try (Statement s = primary.createStatement(); ResultSet rs = s.executeQuery("SELECT * FROM " + table)) {
            int columns = rs.getMetaData().getColumnCount();
            List<String> names = new ArrayList<>();
            List<String> marks = new ArrayList<>();
            for (int i = 1; i <= columns; i++) {
                names.add(rs.getMetaData().getColumnName(i));
                marks.add("?");
            }
            try (PreparedStatement ps = fallback.prepareStatement("INSERT INTO " + table + " ("
                    + String.join(",", names) + ") VALUES (" + String.join(",", marks) + ")")) {
                while (rs.next()) {
                    for (int i = 1; i <= columns; i++) {
                        ps.setObject(i, rs.getObject(i));
                    }
                    ps.executeUpdate();
                }
            }
        }
    }

    @Test
    @DisplayName("mirrors the primary schema into the fallback with upper-case names and identity columns")
    void mirrorsSchema() throws Exception {
        assertEquals(2, scalar(fallback, "SELECT COUNT(*) FROM USERS"));
        assertEquals(2, scalar(fallback, "SELECT COUNT(*) FROM EXPENSES"));

        // Unquoted SQL, as Hibernate writes it, must reach the mirrored tables.
        exec(fallback, "INSERT INTO users (email, name) VALUES ('c@example.com', 'Chitra')");
        long newId = scalar(fallback, "SELECT id FROM users WHERE email = 'c@example.com'");
        assertTrue(newId > FallbackSyncEngine.ID_GAP, "fallback ids must start well above the primary's: " + newId);
    }

    @Test
    @DisplayName("reports no changes right after a refresh")
    void noChangesAfterRefresh() throws Exception {
        assertEquals(0, engine.pendingChanges(fallback));
        assertTrue(engine.syncBack(fallback, primary).isEmpty());
    }

    @Test
    @DisplayName("writes rows created in the fallback to the primary, parents before children, keeping their ids")
    void insertsAreMergedInDependencyOrder() throws Exception {
        exec(fallback, "INSERT INTO users (email, name) VALUES ('c@example.com', 'Chitra')");
        long userId = scalar(fallback, "SELECT id FROM users WHERE email = 'c@example.com'");
        exec(fallback, "INSERT INTO categories (name, user_id) VALUES ('Travel', " + userId + ")");
        long categoryId = scalar(fallback, "SELECT id FROM categories WHERE name = 'Travel'");
        exec(fallback, "INSERT INTO expenses (amount, description, spent_on, created_at, recurring, user_id, category_id) "
                + "VALUES (45.25, 'Bus pass', DATE '2026-10-05', TIMESTAMP '2026-10-05 08:00:00', FALSE, "
                + userId + ", " + categoryId + ")");

        assertEquals(3, engine.pendingChanges(fallback));
        SyncResult result = engine.syncBack(fallback, primary);

        assertEquals(3, result.inserted());
        assertEquals(0, result.conflicts());
        assertEquals(1, scalar(primary, "SELECT COUNT(*) FROM users WHERE id = " + userId));
        assertEquals(1, scalar(primary, "SELECT COUNT(*) FROM expenses WHERE user_id = " + userId + " AND category_id = " + categoryId));
        assertEquals(new BigDecimal("45.25"), decimal(primary, "SELECT amount FROM expenses WHERE description = 'Bus pass'"));
        assertEquals(0, engine.pendingChanges(fallback));
    }

    @Test
    @DisplayName("applies edits made in the fallback but leaves rows the fallback never touched alone")
    void updatesOnlyTouchedRows() throws Exception {
        exec(fallback, "UPDATE expenses SET amount = 130.00, description = 'Lunch with team' WHERE id = 1");
        // The primary changed a different row after the last refresh, just before it went down.
        exec(primary, "UPDATE expenses SET description = 'Rent (edited in primary)' WHERE id = 2");

        SyncResult result = engine.syncBack(fallback, primary);

        assertEquals(1, result.updated());
        assertEquals(new BigDecimal("130.00"), decimal(primary, "SELECT amount FROM expenses WHERE id = 1"));
        assertEquals("Lunch with team", string(primary, "SELECT description FROM expenses WHERE id = 1"));
        assertEquals("Rent (edited in primary)", string(primary, "SELECT description FROM expenses WHERE id = 2"));
    }

    @Test
    @DisplayName("removes rows deleted in the fallback")
    void deletesAreMerged() throws Exception {
        exec(fallback, "DELETE FROM expenses WHERE id = 2");

        SyncResult result = engine.syncBack(fallback, primary);

        assertEquals(1, result.deleted());
        assertEquals(0, scalar(primary, "SELECT COUNT(*) FROM expenses WHERE id = 2"));
        assertEquals(1, scalar(primary, "SELECT COUNT(*) FROM expenses WHERE id = 1"));
    }

    @Test
    @DisplayName("only sends writes made since the previous merge")
    void secondMergeOnlySeesNewWrites() throws Exception {
        exec(fallback, "UPDATE expenses SET amount = 1.00 WHERE id = 1");
        assertEquals(1, engine.syncBack(fallback, primary).updated());
        assertTrue(engine.syncBack(fallback, primary).isEmpty());

        exec(fallback, "UPDATE expenses SET amount = 2.00 WHERE id = 1");
        SyncResult again = engine.syncBack(fallback, primary);
        assertEquals(1, again.updated());
        assertEquals(new BigDecimal("2.00"), decimal(primary, "SELECT amount FROM expenses WHERE id = 1"));
    }

    @Test
    @DisplayName("records a row the primary rejects as a conflict and still merges everything else")
    void conflictsAreRecordedNotFatal() throws Exception {
        // Someone registered this email in the primary after the last refresh; the fallback does not know.
        exec(primary, "INSERT INTO users (email, name) VALUES ('dup@example.com', 'Primary Dup')");
        exec(fallback, "INSERT INTO users (email, name) VALUES ('dup@example.com', 'Fallback Dup')");
        exec(fallback, "UPDATE expenses SET amount = 7.00 WHERE id = 1");

        SyncResult result = engine.syncBack(fallback, primary);

        assertEquals(1, result.conflicts());
        assertEquals(1, result.updated());
        assertEquals(1, engine.conflictCount(fallback));
        assertEquals(new BigDecimal("7.00"), decimal(primary, "SELECT amount FROM expenses WHERE id = 1"));
        assertEquals("Primary Dup", string(primary, "SELECT name FROM users WHERE email = 'dup@example.com'"));
        assertEquals("USERS", string(fallback, "SELECT \"table_name\" FROM \"fb_conflicts\""),
                "fb_conflicts holds the rejected row");
        // It is reported once, not retried forever.
        assertEquals(0, engine.pendingChanges(fallback));
    }

    @Test
    @DisplayName("treats a row that is already in the primary as already merged")
    void existingRowsAreSkipped() throws Exception {
        exec(fallback, "INSERT INTO categories (name, user_id) VALUES ('Fuel', 1)");
        long categoryId = scalar(fallback, "SELECT id FROM categories WHERE name = 'Fuel'");
        // A previous attempt already wrote it to the primary before the baseline could advance.
        exec(primary, "INSERT INTO categories (id, name, user_id) VALUES (" + categoryId + ", 'Fuel', 1)");

        SyncResult result = engine.syncBack(fallback, primary);

        assertEquals(1, result.skipped());
        assertEquals(0, result.conflicts());
        assertEquals(1, scalar(primary, "SELECT COUNT(*) FROM categories WHERE id = " + categoryId));
    }

    @Test
    @DisplayName("reports an id the primary reused for a different row instead of silently skipping it")
    void reusedIdIsAConflict() throws Exception {
        exec(fallback, "INSERT INTO categories (id, name, user_id) VALUES (50, 'Fallback row', 1)");
        exec(primary, "INSERT INTO categories (id, name, user_id) VALUES (50, 'Different row in primary', 2)");

        SyncResult result = engine.syncBack(fallback, primary);

        assertEquals(0, result.skipped());
        assertEquals(1, result.conflicts());
        assertEquals("Different row in primary", string(primary, "SELECT name FROM categories WHERE id = 50"));
        assertEquals(1, engine.conflictCount(fallback));
    }

    @Test
    @DisplayName("picks up columns added to the primary schema")
    void addsMissingColumns() throws Exception {
        exec(primary, "ALTER TABLE users ADD COLUMN currency VARCHAR(10)");
        engine.ensureSchema(primary, fallback);

        exec(fallback, "UPDATE users SET currency = 'INR' WHERE id = 1");
        assertEquals("INR", string(fallback, "SELECT currency FROM users WHERE id = 1"));
    }

    @Test
    @DisplayName("does not mistake a new fallback column for an edit to every row")
    void newColumnsDoNotLookLikeChanges() throws Exception {
        exec(primary, "ALTER TABLE users ADD COLUMN currency VARCHAR(10)");
        engine.ensureSchema(primary, fallback);
        assertFalse(engine.pendingChanges(fallback) > 0, "adding a column must not register as row edits");
    }

    @Test
    @DisplayName("repairSchema converts INTEGER request_json in WEBAUTHN_CHALLENGES to TEXT")
    void repairsWebAuthnColumnTypes() throws Exception {
        exec(fallback, "CREATE TABLE IF NOT EXISTS WEBAUTHN_CHALLENGES (ID VARCHAR(64) PRIMARY KEY, REQUEST_JSON INTEGER NOT NULL)");
        engine.ensureSupportTables(fallback);

        // Inserting a JSON string should now succeed because the column was altered to TEXT
        exec(fallback, "INSERT INTO WEBAUTHN_CHALLENGES (ID, REQUEST_JSON) VALUES ('c1', '{\"challenge\":\"test\"}')");
        assertEquals("{\"challenge\":\"test\"}", string(fallback, "SELECT REQUEST_JSON FROM WEBAUTHN_CHALLENGES WHERE ID = 'c1'"));
    }

    // ------------------------------------------------------------ helpers

    private static void exec(Connection c, String sql) throws SQLException {
        try (Statement s = c.createStatement()) {
            s.execute(sql);
        }
    }

    private static long scalar(Connection c, String sql) throws SQLException {
        try (Statement s = c.createStatement(); ResultSet rs = s.executeQuery(sql)) {
            assertTrue(rs.next(), "no row for: " + sql);
            return rs.getLong(1);
        }
    }

    private static String string(Connection c, String sql) throws SQLException {
        try (Statement s = c.createStatement(); ResultSet rs = s.executeQuery(sql)) {
            assertTrue(rs.next(), "no row for: " + sql);
            return rs.getString(1);
        }
    }

    private static BigDecimal decimal(Connection c, String sql) throws SQLException {
        try (Statement s = c.createStatement(); ResultSet rs = s.executeQuery(sql)) {
            assertTrue(rs.next(), "no row for: " + sql);
            return rs.getBigDecimal(1);
        }
    }
}
